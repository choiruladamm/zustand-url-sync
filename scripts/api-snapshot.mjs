// Regenerates api/public-api.md, one of the frozen snapshots.
//   --write  overwrite it
//   --check  regenerate into memory, diff, exit 1 on drift
//
// Requires `pnpm build` to have run: the snapshot is derived from dist/, never from src/.

import { existsSync } from 'node:fs'
import { readFile, writeFile } from 'node:fs/promises'
import { join } from 'node:path'
import { fileURLToPath } from 'node:url'

const root = fileURLToPath(new URL('..', import.meta.url))
const dist = join(root, 'dist')
const mode = process.argv.includes('--write') ? 'write' : 'check'

if (!existsSync(dist)) {
  console.error('[api-snapshot] dist/ missing — run `pnpm build` first.')
  process.exit(1)
}

/**
 * Every entrypoint declared in the generated exports map, in a stable order.
 * tsdown emits no explicit `types` condition — TypeScript resolves `x.js` to the sibling
 * `x.d.ts`, and attw's node16 profile confirms that. So derive the path the same way.
 */
async function entrypoints() {
  const pkg = JSON.parse(await readFile(join(root, 'package.json'), 'utf8'))
  const out = []
  for (const [subpath, cond] of Object.entries(pkg.exports ?? {})) {
    if (typeof cond === 'string') continue
    const types = cond.import?.types ?? cond.types ?? cond.import?.replace(/\.js$/, '.d.ts')
    if (typeof types === 'string' && types.endsWith('.d.ts')) {
      out.push({ subpath, types: types.replace(/^\.\//, '') })
    }
  }
  return out.sort((a, b) => a.subpath.localeCompare(b.subpath))
}

async function publicApi() {
  const eps = await entrypoints()
  const lines = [
    '# Public API',
    '',
    '<!-- GENERATED by `pnpm api:update`. Do not edit. A diff here is a semver decision:',
    '     added export -> minor, changed or removed export -> major. -->',
    '',
  ]
  if (eps.length === 0) lines.push('_No entrypoints declare types yet._', '')
  for (const ep of eps) {
    const dts = (await readFile(join(root, ep.types), 'utf8')).trim()
    const specifier = ep.subpath === '.' ? '' : ep.subpath.slice(1)
    lines.push(`## \`zustand-url-sync${specifier}\``, '', '```ts')
    lines.push(dts.length > 0 ? dts : '// exports nothing')
    lines.push('```', '')
  }
  return `${lines.join('\n').trimEnd()}\n`
}

// `api/wire-format.md` is generated by src/codecs/wire-format.test.ts, which needs the real
// codecs rather than the built bundle. `pnpm test` gates it; this script owns the other snapshot.
const artifacts = [['api/public-api.md', await publicApi()]]

let drifted = false
for (const [path, next] of artifacts) {
  const abs = join(root, path)
  if (mode === 'write') {
    await writeFile(abs, next)
    console.log(`[api-snapshot] wrote ${path}`)
    continue
  }
  const current = existsSync(abs) ? await readFile(abs, 'utf8') : ''
  if (current !== next) {
    drifted = true
    console.error(`[api-snapshot] ${path} is out of date. Run \`pnpm api:update\` and review the`)
    console.error('              diff — it is the semver decision, not a formality.')
  }
}
process.exit(drifted ? 1 : 0)
